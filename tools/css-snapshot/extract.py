#!/usr/bin/env python3
"""Pulls the CSS the UnoCSS runtime generated out of a dumped DOM and writes utilities.css."""
import html
import re
import sys

src, out = sys.argv[1], sys.argv[2]
dom = open(src, encoding="utf-8").read()
m = re.search(r'<pre id="uno-snapshot">(.*?)</pre>', dom, re.S)
if not m:
    sys.exit("snapshot not found in the dumped page: is the site running, and does /?uno=snapshot load?")
css = html.unescape(m.group(1)).strip()
if css.count("{") < 100:
    sys.exit("snapshot looks empty (%d rules)" % css.count("{"))
# One rule per line is already how the runtime prints it; drop the layer comments and blank lines.
css = "\n".join(line for line in css.splitlines() if line.strip() and not line.startswith("/* layer:"))
# Safari still needs the -webkit- prefix on these (user-select everywhere, backdrop-filter before 18).
css = re.sub(r"(?<![-\w])(user-select|backdrop-filter):([^;}]+)(;|(?=}))", lambda m: "-webkit-%s:%s;%s:%s%s" % (m.group(1), m.group(2), m.group(1), m.group(2), m.group(3)), css)
header = "/* Generated by tools/css-snapshot/snapshot.sh from the UnoCSS runtime. Do not edit. */\n"
open(out, "w", encoding="utf-8").write(header + css + "\n")
print("wrote %s: %d bytes, %d rules" % (out, len(css), css.count("{")))
